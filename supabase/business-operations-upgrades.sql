-- Business operations foundation for an existing NEW Supabase project.
-- This migration does not create orders, take payments, or change stock for sales.
-- It grants profile management to owners and records an allowlisted audit trail.

-- Let the owner create/edit staff profiles without allowing users to change their
-- own ID or giving administrators/salespeople profile-management rights.
grant insert (id, full_name, role, is_active) on public.profiles to authenticated;
grant update (full_name, role, is_active) on public.profiles to authenticated;

-- Remove direct audit writes: all audit entries must be generated by the trigger below.
drop policy if exists "authenticated write audit logs" on public.audit_logs;
revoke insert, update, delete, truncate on public.audit_logs from anon, authenticated;
grant select on public.audit_logs to authenticated;

-- Disable direct table writes for sales until the atomic sale/order function and UI
-- are delivered. Database tables and permissive policies alone are not a safe POS.
drop policy if exists "admins and salespeople create orders" on public.orders;
drop policy if exists "admins manage orders" on public.orders;
drop policy if exists "admins and salespeople create order items" on public.order_items;
drop policy if exists "admins update order items" on public.order_items;

create or replace function public.write_business_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old jsonb := '{}'::jsonb;
  v_new jsonb := '{}'::jsonb;
  v_allowed text[];
  v_before jsonb := '{}'::jsonb;
  v_after jsonb := '{}'::jsonb;
  v_id text;
  v_actor uuid;
  v_key text;
begin
  -- Public online buyers may not have staff profiles. Store NULL in that case
  -- so the audit row respects its profile foreign key without blocking checkout.
  select p.id into v_actor from public.profiles p
  where p.id = (select auth.uid()) and p.is_active = true;
  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;
  v_id := coalesce(v_new->>'id', v_old->>'id', v_new->>'user_id', v_old->>'user_id');

  -- Allowlist operational fields only. Customer contact data, addresses,
  -- auth/password data, and free-form notes are intentionally excluded.
  case tg_table_name
    when 'products' then v_allowed := array['name','category_id','retail_price','wholesale_price','cost_price','stock_quantity','is_published','is_active'];
    when 'product_variants' then v_allowed := array['product_id','variant_name','attributes','retail_price','wholesale_price','cost_price','stock_quantity','is_active'];
    when 'orders' then v_allowed := array['order_number','sales_channel','order_status','payment_status','payment_method','subtotal','discount_total','delivery_fee','total'];
    when 'order_items' then v_allowed := array['order_id','product_id','variant_id','unit_cost_snapshot','unit_price','quantity','discount','line_total'];
    when 'expenses' then v_allowed := array['expense_date','category','amount','payment_method'];
    when 'deliveries' then v_allowed := array['order_id','assigned_to','delivery_status','delivery_fee'];
    when 'profiles' then v_allowed := array['role','is_active'];
    else raise exception 'Audit trigger is not configured for table %', tg_table_name;
  end case;

  foreach v_key in array v_allowed loop
    if tg_op <> 'INSERT' and v_old ? v_key then v_before := v_before || jsonb_build_object(v_key, v_old->v_key); end if;
    if tg_op <> 'DELETE' and v_new ? v_key then v_after := v_after || jsonb_build_object(v_key, v_new->v_key); end if;
  end loop;

  if tg_op = 'UPDATE' and v_before = v_after then return new; end if;

  insert into public.audit_logs (actor_id, action, entity_type, entity_id, details)
  values (v_actor, lower(tg_op), tg_table_name, v_id,
          jsonb_build_object('before', v_before, 'after', v_after));

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.write_business_audit_log() from public, anon, authenticated;

drop trigger if exists audit_products on public.products;
create trigger audit_products after insert or update or delete on public.products
for each row execute function public.write_business_audit_log();

drop trigger if exists audit_product_variants on public.product_variants;
create trigger audit_product_variants after insert or update or delete on public.product_variants
for each row execute function public.write_business_audit_log();

drop trigger if exists audit_orders on public.orders;
create trigger audit_orders after insert or update or delete on public.orders
